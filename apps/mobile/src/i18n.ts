const dictionaries: Record<Language, Record<TranslationKey, string>> = { ru, kk, en };

interface I18nState {
  language: Language;
  setLanguage: (language: Language) => Promise<void>;
  hydrate: () => Promise<void>;
}

export const useI18nStore = create<I18nState>((set) => ({
  language: 'ru',
  setLanguage: async (language) => {
    set({ language });
    await SecureStore.setItemAsync('klyvo.language', language);
  },
  hydrate: async () => {
    const saved = await SecureStore.getItemAsync('klyvo.language');
    if (saved === 'ru' || saved === 'kk' || saved === 'en') set({ language: saved });
  },
}));

export function translate(language: Language, key: TranslationKey) {
  return dictionaries[language][key];
}

export type Translate = (key: TranslationKey) => string;

/**
 * Ошибки приходят с сервера по-английски. Здесь код ошибки превращается
 * в понятную фразу на языке интерфейса — англоязычных сообщений пользователь больше не видит.
 */
const errorKeys: Record<string, TranslationKey> = {
  NETWORK_ERROR: 'errNetwork',
  INSUFFICIENT_CREDITS: 'errInsufficientCredits',
  PROMPT_REJECTED: 'errPromptRejected',
  ASSET_NOT_FOUND: 'errAssetNotFound',
  IMAGE_REQUIRED: 'errUnsupportedMedia',
  FILE_TOO_LARGE: 'errFileTooLarge',
  UNSUPPORTED_MEDIA: 'errUnsupportedMedia',
  FILE_REQUIRED: 'errUnsupportedMedia',
  UNAUTHORIZED: 'errUnauthorized',
  INVALID_REFRESH_TOKEN: 'errUnauthorized',
  EMAIL_TAKEN: 'errEmailTaken',
  INVALID_CREDENTIALS: 'errInvalidCredentials',
  VALIDATION_ERROR: 'errValidation',
  NOT_FOUND: 'errNotFound',
  VIDEO_NOT_FOUND: 'errNotFound',
  GENERATION_NOT_FOUND: 'errNotFound',
  GENERATION_TIMEOUT: 'errTimeout',
  PROVIDER_CREATE_FAILED: 'errProvider',
  PROVIDER_TASK_FAILED: 'errProvider',
  MOCK_PROVIDER_ERROR: 'errProvider',
  PAYMENT_FAILED: 'genericError',
  PAYMENT_NOT_VERIFIED: 'genericError',
  INTERNAL_ERROR: 'errServer',
};

export function apiErrorMessage(language: Language, error: unknown): string {
  const code = error && typeof error === 'object' && 'code' in error ? String(error.code) : '';
  const key = errorKeys[code];
  if (key) return dictionaries[language][key];
  return dictionaries[language].genericError;
}

export function useTranslation() {
  const language = useI18nStore((state) => state.language);
  return {
    language,
    t: (key: TranslationKey) => dictionaries[language][key],
    tError: (error: unknown) => apiErrorMessage(language, error),
  };
}
